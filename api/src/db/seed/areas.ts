// Idempotent: skips names already present in group 'area'. Also runnable on its own
// (bun src/db/seed/areas.ts) since index.ts truncates every table first.
export async function seedAreas() {
  let inserted = 0
  for (const name of AREAS) {
    const existing = await db.query.categories.findFirst({
      where: (t, { eq, and, isNull }) =>
        and(eq(t.group, 'area'), eq(t.name, name), isNull(t.deletedAt)),
    })
    if (existing) continue
    await db.insert(categories).values({ group: 'area', name, status: 'active' })
    inserted++
  }
  console.log(
    `  categories[area]: ${inserted} inserted, ${AREAS.length - inserted} already existed`,
  )
}

if (import.meta.main) {
  await seedAreas()
  await client.end()
}
